# --- IMPORTS ---
import pandas as pd
import numpy as np
import string
import matplotlib.pyplot as plt
import seaborn as sns
import nltk
from nltk.corpus import stopwords
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import MultinomialNB
from sklearn.svm import SVC
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
from wordcloud import WordCloud

# Download NLTK data (stopwords)
nltk.download('stopwords')

print("- 1. DATA LOADING & PREPARATION -")

# CONFIGURATION: Local File Loading
file_name = 'spam.csv'

try:
    print(f"Attempting to load '{file_name}' locally...")
    df = pd.read_csv(file_name, encoding='latin-1')
except FileNotFoundError:
    print(f"ERROR: File '{file_name}' not found.")
    print("Please ensure the dataset file is in the same folder as this script.")
    raise
except Exception as e:
    print(f"Encoding error, trying utf-8... ({e})")
    df = pd.read_csv(file_name, encoding='utf-8')

# Rename and clean columns
df = df.iloc[:, :2]
df.columns = ['label', 'text']
df = df.drop_duplicates(keep='first')
print(f"Dataset Loaded Successfully: {len(df)} unique messages.")
print("Class Distribution:")
print(df['label'].value_counts())

# --- 2. PREPROCESSING PIPELINE ---
def text_process(mess):
    nopunc = [char for char in mess if char not in string.punctuation]
    nopunc = ''.join(nopunc)
    return [word for word in nopunc.split() if word.lower() not in stopwords.words('english')]

print("\n- 3. FEATURE EXTRACTION (TF-IDF) -")
X_train, X_test, y_train, y_test = train_test_split(df['text'], df['label'], test_size=0.2, random_state=42)

print("Vectorizing text data...")
tfidf_transformer = TfidfVectorizer(analyzer=text_process)
X_train_tfidf = tfidf_transformer.fit_transform(X_train)
X_test_tfidf = tfidf_transformer.transform(X_test)
print(f"Matrix Created. Shape: {X_train_tfidf.shape}")

# --- 4. MODEL TRAINING & COMPARISON ---
print("\n- 4. TRAINING MODELS -")
models = {
    "Naive Bayes": MultinomialNB(),
    "Support Vector Machine (SVM)": SVC(kernel='linear'),
    "Random Forest": RandomForestClassifier(n_estimators=100, random_state=42)
}

results = {}
best_model = None
best_accuracy = 0.0
best_preds = []

for name, model in models.items():
    print(f"\nTraining {name}...")
    model.fit(X_train_tfidf, y_train)
    preds = model.predict(X_test_tfidf)
    acc = accuracy_score(y_test, preds)
    results[name] = acc

    # --- PRINT DETAILED REPORT ---
    print(f"- RESULTS FOR {name} -")
    print(f"Accuracy: {acc:.4f}")
    print("Classification Report:")
    print(classification_report(y_test, preds))
    print("-" * 60)

    if acc > best_accuracy:
        best_accuracy = acc
        best_model = model
        best_preds = preds

print("\n- FINAL LEADERBOARD -")
results_df = pd.DataFrame(list(results.items()), columns=['Model', 'Accuracy'])
print(results_df.sort_values(by='Accuracy', ascending=False))

# --- 5. VISUALIZATION (SEPARATE IMAGES) ---
print("\n- 5. GENERATING VISUALIZATIONS -")

# IMAGE 1: Confusion Matrix
print("Generating Image 1: Confusion Matrix...")
plt.figure(figsize=(8, 6))
cm = confusion_matrix(y_test, best_preds)
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=['Ham', 'Spam'], yticklabels=['Ham', 'Spam'])
plt.title(f'Confusion Matrix ({results_df.sort_values(by="Accuracy", ascending=False).iloc[0,0]})')
plt.xlabel('Predicted Label')
plt.ylabel('True Label')
plt.show()

# IMAGE 2: Spam WordCloud
print("Generating Image 2: Spam WordCloud...")
try:
    plt.figure(figsize=(10, 8))
    spam_words = ' '.join(list(df[df['label'] == 'spam']['text']))
    spam_cloud = WordCloud(width=800, height=800, background_color='black').generate(spam_words)
    plt.imshow(spam_cloud, interpolation='bilinear')
    plt.title('Most Frequent Words in SPAM')
    plt.axis('off')
    plt.show()
except Exception as e:
    print(f"Could not generate Spam WordCloud: {e}")

# IMAGE 3: Ham WordCloud
print("Generating Image 3: Ham WordCloud...")
try:
    plt.figure(figsize=(10, 8))
    ham_words = ' '.join(list(df[df['label'] == 'ham']['text']))
    ham_cloud = WordCloud(width=800, height=800, background_color='white').generate(ham_words)
    plt.imshow(ham_cloud, interpolation='bilinear')
    plt.title('Most Frequent Words in HAM (Normal Messages)')
    plt.axis('off')
    plt.show()
except Exception as e:
    print(f"Could not generate Ham WordCloud: {e}")

# --- 6. LIVE TEST SYSTEM ---
print("\n- 6. LIVE SIMULATION -")
def predict_message(message):
    message_tfidf = tfidf_transformer.transform([message])
    prediction = best_model.predict(message_tfidf)[0]
    return prediction

test_msgs = [
    "URGENT! You have won a 1 week FREE membership in our Prize Jackpot! Txt the word: CLAIM to No: 81010",
    "Hello, are we still meeting for lunch tomorrow?",
    "Your account has been credited with 500 free text messages. Call now!"
]

for msg in test_msgs:
    print(f"Input: '{msg}'")
    print(f"Prediction: --> {predict_message(msg).upper()}")
    print("-" * 40)